import streamlit as st
import pandas as pd
import joblib

from reportlab.platypus import SimpleDocTemplate, Paragraph
from reportlab.lib.styles import getSampleStyleSheet
import tempfile

# -----------------------------
# Page Configuration
# -----------------------------
st.set_page_config(
    page_title="Heart Disease Prediction",
    page_icon="❤️",
    layout="wide",
    initial_sidebar_state="collapsed"
)
# -----------------------------
# Load Model
# -----------------------------
@st.cache_resource
def load_model():
    return joblib.load("models/heart_model.pkl")

model = load_model()

# -----------------------------
# PDF Report Generator
# -----------------------------
def generate_pdf(patient_name, age, sex, trestbps, chol, thalach, risk, recommendation):
    temp = tempfile.NamedTemporaryFile(delete=False, suffix=".pdf")

    doc = SimpleDocTemplate(temp.name)

    styles = getSampleStyleSheet()

    story = []

    story.append(Paragraph("<b>Heart Disease Prediction Report</b>", styles["Title"]))

    story.append(Paragraph(f"<b>Patient Name:</b> {patient_name}", styles["BodyText"]))    
    story.append(Paragraph(f"<b>Gender:</b> {'Male' if sex else 'Female'}", styles["BodyText"]))
    story.append(Paragraph(f"<b>Blood Pressure:</b> {trestbps} mmHg", styles["BodyText"]))
    story.append(Paragraph(f"<b>Cholesterol:</b> {chol} mg/dL", styles["BodyText"]))
    story.append(Paragraph(f"<b>Maximum Heart Rate:</b> {thalach} bpm", styles["BodyText"]))

    story.append(Paragraph("<br/>", styles["BodyText"]))

    story.append(Paragraph(f"<b>Risk Score:</b> {risk:.1f}%", styles["BodyText"]))

    story.append(Paragraph(f"<b>Recommendation:</b> {recommendation}", styles["BodyText"]))

    story.append(Paragraph("<br/>", styles["BodyText"]))

    story.append(Paragraph(
        "This prediction is generated by a machine learning model and is for educational purposes only. It is not medical advice.",
        styles["Italic"]
    ))

    doc.build(story)

    return temp.name
